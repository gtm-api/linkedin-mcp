#!/usr/bin/env node
// Build the bundled support-KB index from the gtm.ai monorepo markdown corpus.
//
//   node bin/build-kb-index.mjs
//
// Reads   ../../../customer_success/kb/{articles,qa}/*.md   (override: KB_DIR env)
// Writes  packages/mcp.support/kb_articles/kb-index.ts      (generated module)
//
// _reference/ is deliberately NOT indexed (legacy GetSales corpus - see
// SUPPORT_AGENT_PLAN.md §1.3). Run after every KB edit; wrangler dev hot-reloads.
// The Vectorize (semantic) side is bin/vectorize-kb.mjs - same corpus/chunking.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCorpus } from './lib/kb-corpus.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const kbDir = process.env.KB_DIR ?? resolve(repoRoot, '../../../customer_success/kb');
const outFile = join(repoRoot, 'packages/mcp.support/kb_articles/kb-index.ts');

const { articles, chunks } = loadCorpus(kbDir);
if (articles.length === 0) {
  console.error(`No KB markdown found under ${kbDir}/{articles,qa} - index will be empty.`);
}

const generated = [
  '// GENERATED by bin/build-kb-index.mjs. DO NOT EDIT BY HAND.',
  '// Source of truth: gtm.ai monorepo, customer_success/kb/{articles,qa}/*.md.',
  `// Built ${new Date().toISOString()}: ${articles.length} articles, ${chunks.length} chunks.`,
  "import type { KbIndex } from './retriever';",
  '',
  `export const KB_INDEX: KbIndex = ${JSON.stringify({ articles, chunks }, null, 2)};`,
  '',
].join('\n');

writeFileSync(outFile, generated);
console.log(`kb-index.ts written: ${articles.length} articles, ${chunks.length} chunks (from ${kbDir})`);
